import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from src.credentials import SENDER_EMAIL, APP_PASSWORD

def _is_mock_mode():
    """Returns True if no email credentials are set, simulating email sending."""
    return not SENDER_EMAIL or not APP_PASSWORD

def send_email(to_email, subject, body_html):
    """
    Sends an email using standard SMTP. If credentials are missing, 
    it falls back to mock mode and prints to the console.
    """
    if _is_mock_mode():
        print("="*50)
        print(f"MOCK EMAIL ALERT - (Would be sent to {to_email})")
        print(f"Subject: {subject}")
        print("Body:")
        print(body_html)
        print("="*50)
        return True
        
    try:
        msg = MIMEMultipart()
        msg['From'] = SENDER_EMAIL
        msg['To'] = to_email
        msg['Subject'] = subject

        msg.attach(MIMEText(body_html, 'html'))

        # Use Gmail's SMTP server as default logic
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(SENDER_EMAIL, APP_PASSWORD)
        text = msg.as_string()
        server.sendmail(SENDER_EMAIL, to_email, text)
        server.quit()
        return True
    except Exception as e:
        print(f"Error sending email: {e}")
        return False

